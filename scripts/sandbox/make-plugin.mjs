#!/usr/bin/env node
// Write a fake community plugin into the sandbox vault, for reproducing startup/ribbon behaviour.
//
//   node scripts/sandbox/make-plugin.mjs <id> [--ribbon <icon>:<title>]... [--onload-ms <n>]
//
// --ribbon      add a ribbon icon (lucide icon name and tooltip title); repeatable
// --onload-ms   busy-wait this long in onload, to simulate a heavy plugin
//
// Each load is recorded in window.__bpmSandboxLoads as
// { id, startedAt, finishedAt, layoutReady } (ms since page load), so tests can check *when* BPM started it.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SANDBOX = process.env.BPM_SANDBOX ?? path.join(REPO, ".sandbox");

const [id, ...rest] = process.argv.slice(2);
if (!id) {
	console.error("usage: make-plugin.mjs <id> [--ribbon <icon>:<title>]... [--onload-ms <n>]");
	process.exit(2);
}
const ribbons = [];
let onloadMs = 0;
for (let i = 0; i < rest.length; i++) {
	if (rest[i] === "--ribbon") {
		const [icon, ...title] = rest[++i].split(":");
		ribbons.push({ icon, title: title.join(":") || `${id} ${icon}` });
	} else if (rest[i] === "--onload-ms") {
		onloadMs = Number(rest[++i]);
	} else {
		console.error(`unknown argument: ${rest[i]}`);
		process.exit(2);
	}
}

const dir = path.join(SANDBOX, "vault", ".obsidian", "plugins", id);
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "manifest.json"), JSON.stringify({
	id, name: `Sandbox ${id}`, version: "1.0.0", minAppVersion: "1.0.0",
	description: "Fake plugin generated by scripts/sandbox/make-plugin.mjs", author: "sandbox", isDesktopOnly: false,
}, null, "\t") + "\n");
fs.writeFileSync(path.join(dir, "main.js"), `const { Plugin } = require("obsidian");
module.exports = class SandboxPlugin extends Plugin {
	onload() {
		const startedAt = performance.now();
		while (performance.now() - startedAt < ${onloadMs}) { /* simulate a heavy onload */ }
		for (const [icon, title] of ${JSON.stringify(ribbons.map((r) => [r.icon, r.title]))}) {
			this.addRibbonIcon(icon, title, () => {});
		}
		(window.__bpmSandboxLoads ??= []).push({
			id: ${JSON.stringify(id)}, startedAt, finishedAt: performance.now(), layoutReady: this.app.workspace.layoutReady,
		});
	}
};
`);
console.log(dir);
